package com.openzeekr.app.util

import android.content.ComponentName
import android.content.Context
import android.content.pm.PackageManager
import androidx.annotation.DrawableRes
import com.openzeekr.core.R
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow

/**
 * The design of the launcher icon the user picked (Settings > App-icoon), for everything outside
 * the launcher that should match it: the notification small icon and the badge in the app's top
 * bar (0.3.1). Each design is an `<activity-alias>` in the app manifest; exactly one is enabled.
 * A small icon must be a one-colour silhouette, so every design has its own status-bar drawable
 * (generated by branding/icons/status_icons.py); [Design.DEFAULT] keeps the original mark.
 */
object AppBranding {
    enum class Design(val alias: String, @DrawableRes val statusIcon: Int) {
        DEFAULT("LauncherDefault", R.drawable.ic_logo),
        SILHOUET("LauncherSilhouet", R.drawable.ic_stat_silhouet),
        CLOSEUP("LauncherCloseup", R.drawable.ic_stat_closeup),
        LICHTLIJN("LauncherLichtlijn", R.drawable.ic_stat_lichtlijn),
        SLEUTEL("LauncherSleutel", R.drawable.ic_stat_sleutel),
        FOTO("LauncherFoto", R.drawable.ic_stat_foto),
        // 0.3.3: cut from two 7GT studio photos (branding/icons/photo_icons.py)
        VELG("LauncherVelg", R.drawable.ic_stat_velg),
        WIEL("LauncherWiel", R.drawable.ic_stat_wiel),
        FRONT("LauncherFront", R.drawable.ic_stat_front),
        PLAAT("LauncherPlaat", R.drawable.ic_stat_plaat),
        PROFIEL("LauncherProfiel", R.drawable.ic_stat_profiel),
    }

    private val _design = MutableStateFlow<Design?>(null)
    /** The chosen design once known (null until first read): the foreground notification follows it. */
    val design: StateFlow<Design?> = _design.asStateFlow()

    /** Read from the package manager once per process; [onSelected] keeps it current afterwards. */
    fun current(context: Context): Design = _design.value ?: read(context).also { _design.compareAndSet(null, it) }

    @DrawableRes fun statusIcon(context: Context): Int = current(context).statusIcon

    /** Called by the icon picker after it switched the launcher alias. */
    fun onSelected(design: Design) { _design.value = design }

    /**
     * The enabled alias wins; an alias left at its manifest default counts only for [Design.DEFAULT]
     * (the one the manifest enables). Anything unreadable falls back to [Design.DEFAULT].
     */
    internal fun resolve(enabledSetting: (alias: String) -> Int): Design =
        Design.entries.firstOrNull { design ->
            when (enabledSetting(design.alias)) {
                PackageManager.COMPONENT_ENABLED_STATE_ENABLED -> true
                PackageManager.COMPONENT_ENABLED_STATE_DEFAULT -> design == Design.DEFAULT
                else -> false
            }
        } ?: Design.DEFAULT

    private fun read(context: Context): Design = runCatching {
        val pm = context.packageManager
        resolve { alias -> pm.getComponentEnabledSetting(ComponentName(context.packageName, "$ALIAS_PACKAGE.$alias")) }
    }.getOrDefault(Design.DEFAULT)

    /** The aliases live in the app's code namespace, not the (".test"-suffixed) application id. */
    private const val ALIAS_PACKAGE = "com.openzeekr.app"
}
