"""Status-bar (notification) icons for the five launcher designs, plus preview sheets.

Android draws the status-bar icon of a notification as a one-colour silhouette (alpha only), so
each design's monochrome layer (the themed-icon layer written by icons.py) is cropped to its
artwork and fitted into the 22 dp live area of a 24 dp icon. "Huidig" keeps ic_logo.

Run:  python3 branding/icons/status_icons.py   (after icons.py; needs numpy and pillow)
Writes core/src/main/res/drawable/ic_stat_<key>.xml and preview sheets in branding/icons/out/.
"""
import math
import os
import re

import numpy as np
from PIL import Image, ImageDraw, ImageFont

import icons as I

CORE_DRAWABLE = os.path.join(I.ROOT, 'core', 'src', 'main', 'res', 'drawable')
LOGO_XML = os.path.join(CORE_DRAWABLE, 'ic_logo.xml')
LIVE_DP = 22.0   # Material: 24 dp icon, 1 dp padding


def artwork_bbox(ops):
    """Bounding box (dp, in the 108 dp viewport) of the drawn pixels of a monochrome layer."""
    alpha = np.array(I.render(ops))[..., 3]
    ys, xs = np.nonzero(alpha > 8)
    return xs.min() / I.S, ys.min() / I.S, (xs.max() + 1) / I.S, (ys.max() + 1) / I.S


def fit(bbox, box=24.0, live=LIVE_DP):
    """Scale and translation that put [bbox] centred into the live area of a [box] dp icon."""
    x0, y0, x1, y1 = bbox
    s = live / max(x1 - x0, y1 - y0)
    return s, box / 2 - s * (x0 + x1) / 2, box / 2 - s * (y0 + y1) / 2


def status_xml(d):
    s, tx, ty = fit(artwork_bbox(d['mono']))
    body = I.vector_xml(d['mono'])
    paths = body[body.index('    <path'):body.rindex('</vector>')]
    paths = re.sub(r'android:(fill|stroke)Color="#[0-9A-Fa-f]{8}"', r'android:\1Color="#FFFFFFFF"', paths)
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Status-bar icon for the "%s" launcher design. Generated by branding/icons/status_icons.py\n'
            '     from the design\'s monochrome layer; do not edit by hand. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    xmlns:aapt="http://schemas.android.com/aapt"\n'
            '    android:width="24dp" android:height="24dp"\n'
            '    android:viewportWidth="24" android:viewportHeight="24">\n'
            '    <group android:scaleX="%.5f" android:scaleY="%.5f" android:translateX="%.4f" android:translateY="%.4f">\n'
            '%s'
            '    </group>\n'
            '</vector>\n') % (d['name'], s, s, tx, ty, re.sub(r'(?m)^', '    ', paths).rstrip(' '))


# ---------------------------------------------------------------- ic_logo renderer (preview only)
_TOKEN = re.compile(r'[MLQCAZmlqcaz]|-?\d*\.?\d+(?:[eE][-+]?\d+)?')


def _arc_points(p0, rx, ry, phi, large, sweep, p1, n=24):
    (x1, y1), (x2, y2) = p0, p1
    if rx == 0 or ry == 0:
        return [p1]
    phi = math.radians(phi)
    cp, sp = math.cos(phi), math.sin(phi)
    dx, dy = (x1 - x2) / 2, (y1 - y2) / 2
    x1p, y1p = cp * dx + sp * dy, -sp * dx + cp * dy
    lam = x1p ** 2 / rx ** 2 + y1p ** 2 / ry ** 2
    if lam > 1:
        rx, ry = rx * math.sqrt(lam), ry * math.sqrt(lam)
    num = rx ** 2 * ry ** 2 - rx ** 2 * y1p ** 2 - ry ** 2 * x1p ** 2
    den = rx ** 2 * y1p ** 2 + ry ** 2 * x1p ** 2
    co = math.sqrt(max(0.0, num / den)) if den else 0.0
    if large == sweep:
        co = -co
    cxp, cyp = co * rx * y1p / ry, -co * ry * x1p / rx
    cx = cp * cxp - sp * cyp + (x1 + x2) / 2
    cy = sp * cxp + cp * cyp + (y1 + y2) / 2

    def ang(ux, uy, vx, vy):
        return math.atan2(ux * vy - uy * vx, ux * vx + uy * vy)
    t1 = ang(1, 0, (x1p - cxp) / rx, (y1p - cyp) / ry)
    dt = ang((x1p - cxp) / rx, (y1p - cyp) / ry, (-x1p - cxp) / rx, (-y1p - cyp) / ry)
    if not sweep and dt > 0:
        dt -= 2 * math.pi
    elif sweep and dt < 0:
        dt += 2 * math.pi
    out = []
    for k in range(1, n + 1):
        t = t1 + dt * k / n
        out.append((cx + rx * math.cos(t) * cp - ry * math.sin(t) * sp, cy + rx * math.cos(t) * sp + ry * math.sin(t) * cp))
    return out


def _flatten(d):
    toks = _TOKEN.findall(d)
    i, cmd, pts, polys, cur = 0, None, [], [], (0.0, 0.0)

    def num():
        nonlocal i
        v = float(toks[i]); i += 1
        return v
    while i < len(toks):
        if re.match(r'[A-Za-z]', toks[i]):
            cmd = toks[i]; i += 1
        if cmd == 'M':
            if pts:
                polys.append(pts)
            cur = (num(), num()); pts = [cur]; cmd = 'L'
        elif cmd == 'L':
            cur = (num(), num()); pts.append(cur)
        elif cmd == 'Q':
            c, e = (num(), num()), (num(), num())
            pts += [((1 - t) ** 2 * cur[0] + 2 * (1 - t) * t * c[0] + t * t * e[0],
                     (1 - t) ** 2 * cur[1] + 2 * (1 - t) * t * c[1] + t * t * e[1]) for t in np.linspace(0.1, 1, 10)]
            cur = e
        elif cmd == 'C':
            c1, c2, e = (num(), num()), (num(), num()), (num(), num())
            pts += [((1 - t) ** 3 * cur[0] + 3 * (1 - t) ** 2 * t * c1[0] + 3 * (1 - t) * t * t * c2[0] + t ** 3 * e[0],
                     (1 - t) ** 3 * cur[1] + 3 * (1 - t) ** 2 * t * c1[1] + 3 * (1 - t) * t * t * c2[1] + t ** 3 * e[1])
                    for t in np.linspace(0.1, 1, 10)]
            cur = e
        elif cmd == 'A':
            rx, ry, phi, large, sweep, e = num(), num(), num(), num(), num(), (num(), num())
            pts += _arc_points(cur, rx, ry, phi, int(large), int(sweep), e)
            cur = e
        elif cmd in ('Z', 'z'):
            if pts:
                polys.append(pts)
            pts = []
            cmd = None
        else:
            raise ValueError('unsupported path command %r' % cmd)
    if pts:
        polys.append(pts)
    return polys


def render_logo(px, white=False):
    """ic_logo as Android draws it at [px] pixels (green, or white for the status bar)."""
    xml = open(LOGO_XML).read()
    g = re.search(r'scaleX="([\d.]+)".*?translateX="([-\d.]+)" android:translateY="([-\d.]+)"', xml)
    s, tx, ty = float(g.group(1)), float(g.group(2)), float(g.group(3))
    k = 4
    big = Image.new('RGBA', (px * k, px * k), (0, 0, 0, 0))
    dr = ImageDraw.Draw(big)
    f = px * k / 108.0
    for color, d in re.findall(r'fillColor="(#[0-9a-fA-F]{6})" android:pathData="([^"]+)"', xml):
        fill = (255, 255, 255, 255) if white else tuple(int(color[j:j + 2], 16) for j in (1, 3, 5)) + (255,)
        for poly in _flatten(d):
            dr.polygon([((x * s + tx) * f, (y * s + ty) * f) for x, y in poly], fill=fill)
    return big.resize((px, px), Image.LANCZOS)


# ---------------------------------------------------------------- previews
def status_icon(d, px):
    """The generated status-bar icon, rendered white at [px] pixels (what the status bar shows)."""
    s, tx, ty = fit(artwork_bbox(d['mono']))
    full = I.render(d['mono'])               # 108 dp at I.S px/dp
    alpha = np.array(full)[..., 3]
    k = 4
    n = px * k
    out = np.zeros((n, n), dtype=np.uint8)
    # inverse map: icon pixel -> viewport-108 coordinate -> source pixel
    ys, xs = np.mgrid[0:n, 0:n].astype(float)
    vx = ((xs + 0.5) / n * 24 - tx) / s
    vy = ((ys + 0.5) / n * 24 - ty) / s
    sx = np.clip((vx * I.S).astype(int), 0, alpha.shape[1] - 1)
    sy = np.clip((vy * I.S).astype(int), 0, alpha.shape[0] - 1)
    inside = (vx >= 0) & (vx < 108) & (vy >= 0) & (vy < 108)
    out[inside] = alpha[sy[inside], sx[inside]]
    a = Image.fromarray(out, 'L').resize((px, px), Image.LANCZOS)
    img = Image.new('RGBA', (px, px), (255, 255, 255, 0))
    img.putalpha(a)
    return img


def tint(icon, rgb):
    out = Image.new('RGBA', icon.size, rgb + (0,))
    out.putalpha(icon.getchannel('A'))
    return out


def badge(d, px):
    """The top-left app badge: the design as on the home screen, as a rounded square."""
    if d is None:
        card = Image.new('RGBA', (px, px), (0x1F, 0x28, 0x25, 255))
        card.alpha_composite(render_logo(px))
        icon = card
    else:
        full = I.compose(d)
        icon = full.crop((int(18 * I.S), int(18 * I.S), int(90 * I.S), int(90 * I.S))).resize((px, px), Image.LANCZOS)
    k = 4
    m = Image.new('L', (px * k, px * k), 0)
    ImageDraw.Draw(m).rounded_rectangle([0, 0, px * k - 1, px * k - 1], radius=px * k / 3.2, fill=255)
    out = icon.copy()
    out.putalpha(Image.fromarray((np.array(icon.getchannel('A')).astype(float) *
                                  np.array(m.resize((px, px), Image.LANCZOS)).astype(float) / 255).astype(np.uint8)))
    return out


